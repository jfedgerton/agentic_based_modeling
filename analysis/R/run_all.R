# run_all.R
# Runs every R stage in order. Each stage reads only the outputs of earlier stages and stops on a failed check.
# The Python text analysis (python/, run by run_all.sh) must run first: 11_waffle.R reads its output.
# Usage, from the repository root:  Rscript R/run_all.R   (or bash run_all.sh for everything)

PIPELINE_ROOT <- normalizePath(Sys.getenv("PIPELINE_ROOT", unset = "."), mustWork = TRUE)
Sys.setenv(PIPELINE_ROOT = PIPELINE_ROOT)

# ---- Fail early if a package is missing -------------------------------------------------------------------
PKGS <- c("dplyr", "tidyr", "purrr", "readr", "tibble", "jsonlite", "nanoparquet",
          "ggplot2", "patchwork", "scales", "ggalluvial", "RColorBrewer")
missing <- PKGS[!vapply(PKGS, requireNamespace, logical(1), quietly = TRUE)]
if (length(missing) > 0) {
  stop("Missing R packages: ", paste(missing, collapse = ", "),
       "\nInstall with: install.packages(c(", paste0('"', missing, '"', collapse = ", "), "))", call. = FALSE)
}
dir.create(file.path(PIPELINE_ROOT, "logs"), showWarnings = FALSE)
writeLines(capture.output(sessionInfo()), file.path(PIPELINE_ROOT, "logs", "sessionInfo.txt"))

scripts <- c(
  "01_run_index.R",          # one row per run; exclusions (parse failures, benchmark mismatch, duplicate replays)
  "02_timeseries.R",         # stacks every kept run's time_series.csv
  "03_cv_threshold.R",       # recovers the classic civil-violence activation threshold (~0.101)
  "04_interstate_conflict.R",# crisis-bargaining game summaries and main-text table
  "05_cv_longrun.R",         # 500-step civil-violence check
  "06_provider_divergence.R",# steady-state outcomes per run, exact permutation tests, framing interaction
  "07_decision_rules.R",     # PD transition rule, CV activation curves
  "08_figures.R",            # divergence, trajectories, decision rules, parse failures and SM figures
  "09_tables.R",             # Table 2, ED Tables 1-2, table S3
  "10_alluvial.R",           # fig. S4
  "11_waffle.R",             # Fig. 4 waffle (needs derived/text/ from the Python step)
  "12_fig5_crisis.R"         # Fig. 5 crisis game: trajectories and reasons for overstating strength
)

start_time <- Sys.time()
for (s in scripts) {
  cat(sprintf("\n===== %s =====\n", s))
  t0 <- Sys.time()
  local(source(file.path(PIPELINE_ROOT, "R", s), local = TRUE))
  cat(sprintf("===== %s done in %.1fs =====\n", s, as.numeric(Sys.time() - t0, units = "secs")))
}

# ---- Every manuscript item must exist and be fresh ----------------------------------------------------------
MANUSCRIPT <- c(
  "figures/fig1_provider_divergence.pdf", "figures/fig2_trajectories.pdf", "figures/fig3_decision_rules.pdf",
  "figures/fig4_out_of_sample.pdf", "figures/figS_parse_failures.pdf", "figures/fig_waffle_deviations.pdf", "figures/ed1_divergence_triangle.pdf",
  "figures/ed2_cv_longrun.pdf", "figures/ed3_language_vs_provider.pdf", "figures/alluvial_design_2col.pdf",
  "tables/table2_provider_divergence.tex", "tables/table_ic.tex", "tables/ed_table1_framing_interaction.tex",
  "tables/ed_table2_interstate_conflict.tex", "tables/appendixB_run_completeness.tex")
paths <- file.path(PIPELINE_ROOT, MANUSCRIPT)
stale <- MANUSCRIPT[!file.exists(paths) | file.mtime(paths) < start_time]
if (length(stale) > 0) stop("Not regenerated by this run: ", paste(stale, collapse = ", "), call. = FALSE)
cat(sprintf("\nPipeline complete in %.1fs. All %d manuscript figures and tables regenerated.\n",
            as.numeric(Sys.time() - start_time, units = "secs"), length(MANUSCRIPT)))

"""Extract the LLM prompt templates used in the experiments into a table.

Reads src/prompts/{pd,cv,ic}_prompts.py from a checkout of the experiment code
(tag v1.0-experiments, commit 51400c1) with ast -- nothing in the repo is
imported or executed. Writes:
  derived/prompt_text.csv          every template, EN and ZH
  tables/si_prompt_text.tex        LaTeX longtable of the English templates
Usage: python3 -I tools/extract_prompts.py <path_to_prompts_dir> <pipeline_root>
"""
import ast, csv, os, sys

src_dir, root = sys.argv[1], sys.argv[2]

# Hard-coded map from constant name to (game, mode, phase/variant, language, used in main runs)
META = {
    "PD_CALCULATOR_PROMPT": ("PD", "Calculator", "Decision", "en", "yes"),
    "PD_REASONER_PROMPT": ("PD", "Reasoner", "Decision", "en", "yes"),
    "PD_ROLEPLAYER_PROMPT": ("PD", "Role-player", "Decision", "en", "yes"),
    "CV_CALCULATOR_EN_PROMPT": ("CV", "Calculator", "Decision", "en", "yes"),
    "CV_REASONER_EN_PROMPT": ("CV", "Reasoner", "Decision", "en", "yes"),
    "CV_ROLEPLAYER_EN_PROMPT": ("CV", "Role-player", "Decision", "en", "yes"),
    "CV_CALCULATOR_ZH_PROMPT": ("CV", "Calculator", "Decision", "zh", "language robustness only"),
    "CV_REASONER_ZH_PROMPT": ("CV", "Reasoner", "Decision", "zh", "language robustness only"),
    "CV_ROLEPLAYER_ZH_PROMPT": ("CV", "Role-player", "Decision", "zh", "language robustness only"),
    "BLUFFING_HINT": ("IC", "Reasoner and role-player", "Inserted at {BLUFFING_HINT} when bluffing is on", "en", "yes"),
    "IC_CALCULATOR_SIGNAL_PROMPT": ("IC", "Calculator", "Signal", "en", "yes"),
    "IC_CALCULATOR_DECIDE_PROMPT": ("IC", "Calculator", "Decide", "en", "yes"),
    "IC_REASONER_SIGNAL_PROMPT": ("IC", "Reasoner", "Signal", "en", "yes"),
    "IC_REASONER_DECIDE_PROMPT": ("IC", "Reasoner", "Decide", "en", "yes"),
    "IC_ROLEPLAYER_CATEGORICAL_SIGNAL_PROMPT": ("IC", "Role-player", "Signal (categorical)", "en", "yes"),
    "IC_ROLEPLAYER_CATEGORICAL_DECIDE_PROMPT": ("IC", "Role-player", "Decide (categorical)", "en", "yes"),
    "IC_ROLEPLAYER_FREEFORM_SIGNAL_PROMPT": ("IC", "Role-player", "Signal (free-text ablation)", "en", "ablation only (both runs fail parse gate)"),
    "IC_ROLEPLAYER_FREEFORM_DECIDE_PROMPT": ("IC", "Role-player", "Decide (free-text ablation)", "en", "ablation only (both runs fail parse gate)"),
}

rows = []
for g in ["pd", "cv", "ic"]:
    tree = ast.parse(open(os.path.join(src_dir, f"{g}_prompts.py"), encoding="utf-8").read())
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            name = node.targets[0].id
            assert name in META, f"Unmapped prompt constant {name}"
            game, mode, phase, lang, used = META[name]
            # the templates escape literal braces as {{ }} for str.format; show them as the model sees them
            text = node.value.value.replace("{{", "{").replace("}}", "}")
            rows.append(dict(game=game, mode=mode, phase=phase, language=lang, used_in=used,
                             constant=name, n_chars=len(text), text=text))
assert len(rows) == len(META), f"Expected {len(META)} prompts, found {len(rows)}"

with open(os.path.join(root, "derived", "prompt_text.csv"), "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
    w.writeheader(); w.writerows(rows)

def tex_escape(s):
    rep = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "&": r"\&", "%": r"\%",
           "#": r"\#", "_": r"\_\allowbreak{}", "^": r"\^{}", "~": r"\~{}", "×": r"$\times$", "−": "-",
           "—": "--", "–": "--", "≤": r"$\le$", "≥": r"$\ge$", "’": "'", "→": r"$\rightarrow$", "∈": r"$\in$", "…": r"\ldots{}", "·": r"$\cdot$", "≈": r"$\approx$", "“": "``", "”": "''"}
    out = "".join(rep.get(c, c) for c in s)
    return out.replace("\n", r"\newline ")

lines = [
    r"% Generated by tools/extract_prompts.py from tag v1.0-experiments (51400c1). Do not edit by hand.",
    r"% Needs \usepackage{longtable} and \usepackage{array} in the preamble.",
    r"{\footnotesize",
    r"\begin{longtable}{@{}p{0.07\linewidth}p{0.11\linewidth}p{0.12\linewidth}p{0.60\linewidth}@{}}",
    r"\caption{Prompt templates given to LLM agents (English). Braces mark values filled in each round. Chinese civil-violence prompts and the free-text interstate ablation are in the replication files.}\label{tab:si-prompts}\\",
    r"\toprule Game & Mode & Phase & Prompt text \\ \midrule \endfirsthead",
    r"\toprule Game & Mode & Phase & Prompt text \\ \midrule \endhead",
    r"\bottomrule \endfoot",
]
for r in rows:
    if r["language"] != "en" or r["used_in"] != "yes":
        continue
    lines.append(f"{r['game']} & {tex_escape(r['mode'])} & {tex_escape(r['phase'])} & "
                 f"{{\\ttfamily\\raggedright {tex_escape(r['text'].strip())}}} \\\\ \\midrule")
lines += [r"\end{longtable}", "}"]
with open(os.path.join(root, "tables", "si_prompt_text.tex"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"Wrote {len(rows)} prompts to derived/prompt_text.csv and "
      f"{sum(1 for r in rows if r['language']=='en' and r['used_in']=='yes')} to tables/si_prompt_text.tex")
